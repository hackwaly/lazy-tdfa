// Generate the nullable-repetition capture tests using Go's regexp package.
// Run from the repository root:
//   go run scripts/nullable_oracle.go > nullable_go_test.mbt
package main

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
	"unicode/utf16"
)

func utf16Offset(input string, byteOffset int) int {
	return len(utf16.Encode([]rune(input[:byteOffset])))
}

func main() {
	patterns := []string{
		`^(a?)*b$`, `^(a?)+b$`, `^(a?){2,}b$`, `^(a?){3,}b$`,
		`^(a?)*?b$`, `^(a?)+?b$`, `^(a?){2,}?b$`,
		`^(a?){0}b$`, `^(a?){2}b$`, `^(a?){0,3}b$`, `^(a?){0,3}?b$`,
		`^(|a)*`, `^(a|)*`, `^(|a)+`, `^(a|)+?`, `^(|a){2,}`,
		`^(|a)*b`, `^(|a)*?b`, `^(a?|b)*`, `^(a?|b)*$`,
		`^(a*?b*?)*a`, `^(a*?b*?)+a`, `^(a*?b*?){2,}a`,
		`^(a*?b*?){3,}a`, `^(a*?b*?)*?a`, `^(a?b??)*(b*)`,
		`^((a*?b*?))*(a)`, `^((a?)*)*b`, `^((a?)*)*?b`,
		`^(?:(a*?b*?)*a){2}`, `^(()*)*`, `^(){3,}a$`, `^($|a)+?`,
		`((a*?b*?))*(a)`, `^(😀?)*b$`, `^((😀*?b*?))*(😀)`,
	}
	inputs := []string{"", "a", "aa", "aaa", "b", "ab", "aab", "aaab", "baaa", "baaaa", "aab!", "aa!", "baaa!", "x!baaa", "😀b", "😀😀b", "b😀😀😀"}
	fmt.Println("// Generated by: go run scripts/nullable_oracle.go")
	fmt.Println("// Go byte offsets are converted to MoonBit UTF-16 offsets.")
	fmt.Println("///|")
	fmt.Println(`test "nullable repetition matches Go capture priority" {`)
	fmt.Println("  let cases : Array[(String, String, Array[(Int, Int)?]?)] = [")
	for _, pattern := range patterns {
		re := regexp.MustCompile(pattern)
		for _, input := range inputs {
			indices := re.FindStringSubmatchIndex(input)
			result := "None"
			if indices != nil {
				groups := []string{}
				for i := 0; i < len(indices); i += 2 {
					group := "None"
					if indices[i] >= 0 {
						group = fmt.Sprintf("Some((%d, %d))", utf16Offset(input, indices[i]), utf16Offset(input, indices[i+1]))
					}
					groups = append(groups, group)
				}
				result = "Some([" + strings.Join(groups, ", ") + "])"
			}
			fmt.Printf("    (%s, %s, %s),\n", strconv.Quote(pattern), strconv.Quote(input), result)
		}
	}
	fmt.Println(`  ]
  for (pattern, input, expected) in cases {
    let regex = @regex.Regex::unsafe_from_string(pattern)
    for _ in 0..<2 {
      match (regex.execute(input), expected) {
        (None, None) => ()
        (Some(result), Some(groups)) => {
          for index, span in groups {
            let actual = result.group(index).map(group => {
              (group.start_offset(), group.start_offset() + group.length())
            })
            if actual != span {
              fail("capture mismatch: \{pattern} on \{input}, group \{index}")
            }
          }
          assert_eq(result.group(groups.length()), None)
        }
        _ => fail("match mismatch: \{pattern} on \{input}")
      }
    }
  }
}`)
}
